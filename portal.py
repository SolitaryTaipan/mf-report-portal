"""Web portal for the Quantify Capital report engine.

    python portal.py                          -> http://localhost:8000 (this computer only)
    python portal.py --open                   -> also opens it in the browser
    python portal.py --port 8080
    PORTAL_PASSWORD=... python portal.py --host 0.0.0.0     -> on a server (login required)

Environment: PORTAL_HOST, PORT, PORTAL_USER (default "admin"), PORTAL_PASSWORD.
When PORTAL_PASSWORD is set every page needs HTTP Basic login; the portal refuses to listen
on a non-local address without it (reports hold client data). Put HTTPS in front on a server.
Reports are generated by report_engine.py, which fetches live NAVs from mfapi.in on every
run, and saved in reports/.
"""
from __future__ import annotations

import argparse
import base64
import hmac
import json
import os
import sys
import threading
import webbrowser
from datetime import date
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, unquote, urlparse

import report_engine as eng

ROOT = Path(__file__).resolve().parent
REPORTS = ROOT / "reports"
PAGE = ROOT / "portal.html"
MAX_BODY = 100_000
AUTH_USER = os.environ.get("PORTAL_USER", "admin")
AUTH_PASS = os.environ.get("PORTAL_PASSWORD", "")
LOCAL_HOSTS = ("127.0.0.1", "localhost", "::1")

_generate_lock = threading.Lock()       # one report at a time
_schemes: list[dict] | None = None      # scheme list for search suggestions only
_schemes_lock = threading.Lock()


def scheme_index() -> list[dict]:
    global _schemes
    with _schemes_lock:
        if _schemes is None:
            _schemes = eng.fetch_scheme_list()
    return _schemes


def search_schemes(q: str, limit: int = 12) -> list[dict]:
    words = eng.norm(q).split()
    if not words:
        return []
    hits = [s for s in scheme_index()
            if all(any(tok.startswith(w) for tok in s["tokens"]) for w in words)]
    hits.sort(key=lambda s: (len(s["name"]), s["name"]))
    return [{"code": s["code"], "name": s["name"]} for s in hits[:limit]]


def scheme_info(name: str) -> dict:
    """Exact-name lookup plus live NAV history check, so the form can ask for an expected
    return when a fund has under 5 years of NAV (system.md §4)."""
    s = eng.resolve_scheme(name, scheme_index())
    today = date.today()
    _, nav = eng.fetch_nav(s["code"], s["name"], today)
    first = nav.index[0].date()
    return {"ok": True, "name": s["name"], "code": s["code"],
            "first_nav": first.strftime("%d %b %Y"), "short": first > eng.minus_years(today, eng.YEARS)}


def list_reports() -> list[dict]:
    if not REPORTS.exists():
        return []
    files = sorted(REPORTS.glob("*.pdf"), key=lambda p: p.stat().st_mtime, reverse=True)
    return [{"name": p.name, "size_kb": round(p.stat().st_size / 1024)} for p in files[:50]]


class Handler(BaseHTTPRequestHandler):
    server_version = "QCPortal/1.0"

    def _send(self, code: int, body: bytes, ctype: str, extra: dict | None = None):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        for k, v in (extra or {}).items():
            self.send_header(k, v)
        self.end_headers()
        self.wfile.write(body)

    def _json(self, obj, code: int = 200):
        self._send(code, json.dumps(obj, ensure_ascii=False).encode("utf-8"), "application/json; charset=utf-8")

    def _authorized(self) -> bool:
        """HTTP Basic login when PORTAL_PASSWORD is set; sends the 401 itself when it fails."""
        if not AUTH_PASS:
            return True
        h = self.headers.get("Authorization", "")
        ok = False
        if h.startswith("Basic "):
            try:
                user, _, pw = base64.b64decode(h[6:]).decode("utf-8").partition(":")
                ok = (hmac.compare_digest(user.encode(), AUTH_USER.encode())
                      & hmac.compare_digest(pw.encode(), AUTH_PASS.encode()))
            except (ValueError, UnicodeDecodeError):
                ok = False
        if not ok:
            self._send(401, b"Login required", "text/plain",
                       {"WWW-Authenticate": 'Basic realm="MF Report Portal", charset="UTF-8"'})
        return ok

    def do_GET(self):
        url = urlparse(self.path)
        path = url.path
        if path == "/healthz":                          # unauthenticated liveness check
            self._send(200, b"ok", "text/plain")
            return
        if not self._authorized():
            return
        if path in ("/", "/index.html"):
            self._send(200, PAGE.read_bytes(), "text/html; charset=utf-8")
        elif path == "/api/schemes":
            q = parse_qs(url.query).get("q", [""])[0]
            try:
                self._json({"ok": True, "results": search_schemes(q)})
            except eng.EngineError as e:
                self._json({"ok": False, "error": f"ERROR: {e}"})
        elif path == "/api/scheme_info":
            name = parse_qs(url.query).get("name", [""])[0]
            try:
                self._json(scheme_info(name))
            except eng.EngineError as e:
                self._json({"ok": False, "error": f"ERROR: {e}"})
        elif path == "/api/reports":
            self._json({"ok": True, "reports": list_reports()})
        elif path.startswith("/reports/"):
            name = unquote(path[len("/reports/"):])
            allowed = {p.name for p in REPORTS.glob("*.pdf")} if REPORTS.exists() else set()
            if name not in allowed:                      # no path traversal: exact file names only
                self._send(404, b"Not found", "text/plain")
                return
            self._send(200, (REPORTS / name).read_bytes(), "application/pdf",
                       {"Content-Disposition": f"inline; filename*=UTF-8''{path[len('/reports/'):]}"})
        else:
            self._send(404, b"Not found", "text/plain")

    def do_POST(self):
        if not self._authorized():
            return
        if urlparse(self.path).path != "/api/generate":
            self._send(404, b"Not found", "text/plain")
            return
        length = int(self.headers.get("Content-Length") or 0)
        if length <= 0 or length > MAX_BODY:
            self._json({"ok": False, "error": "ERROR: Request is empty or too large."}, 400)
            return
        try:
            raw = json.loads(self.rfile.read(length).decode("utf-8"))
        except (ValueError, UnicodeDecodeError):
            self._json({"ok": False, "error": "ERROR: Request is not valid JSON."}, 400)
            return
        with _generate_lock:
            try:
                lines = eng.run(raw, REPORTS, date.today())
            except eng.EngineError as e:
                self._json({"ok": False, "error": f"ERROR: {e}"})
                return
            except Exception as e:                       # never leave the browser hanging
                self._json({"ok": False, "error": f"ERROR: Unexpected failure ({type(e).__name__}: {e})"})
                return
        self._json({"ok": True, "lines": lines, "file": lines[2].removeprefix("File: ")})

    def log_message(self, fmt, *args):
        sys.stderr.write("[portal] " + (fmt % args) + "\n")


def main():
    ap = argparse.ArgumentParser(description="Quantify Capital MF Report Portal")
    ap.add_argument("--host", default=os.environ.get("PORTAL_HOST", "127.0.0.1"),
                    help="address to listen on (default 127.0.0.1; 0.0.0.0 on a server)")
    ap.add_argument("--port", type=int, default=int(os.environ.get("PORT", "8000")))
    ap.add_argument("--open", action="store_true", help="open the portal in the default browser")
    ap.add_argument("--allow-no-auth", action="store_true",
                    help="listen on a non-local address without PORTAL_PASSWORD (only behind a proxy that logs users in)")
    a = ap.parse_args()
    if a.host not in LOCAL_HOSTS and not AUTH_PASS and not a.allow_no_auth:
        print(f"Refusing to listen on {a.host} without a password: reports contain client data. "
              f"Set PORTAL_PASSWORD (and optionally PORTAL_USER), or pass --allow-no-auth if a "
              f"reverse proxy already handles login.")
        sys.exit(2)
    try:
        httpd = ThreadingHTTPServer((a.host, a.port), Handler)
    except OSError:
        print(f"Port {a.port} is already in use. Is the portal already running? "
              f"Try http://localhost:{a.port} or start with --port 8080")
        sys.exit(1)
    url = f"http://{'localhost' if a.host in LOCAL_HOSTS else a.host}:{a.port}"
    print(f"MF Report Portal running at {url}{' (login required)' if AUTH_PASS else ''}  (Ctrl+C to stop)",
          flush=True)
    threading.Thread(target=scheme_index, daemon=True).start()   # warm up search
    if a.open:
        webbrowser.open(url)
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nStopped.")


if __name__ == "__main__":
    main()
